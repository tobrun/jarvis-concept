"""Render this Jarvis from its profile and adapters, and validate both.

Usage:
  bootstrap.py render              write every generated file from profile/jarvis.profile.yaml
  bootstrap.py validate            check the profile and every adapter; exit 1 listing the problems
  bootstrap.py adapters            list the shipped source and delivery adapters as JSON
  bootstrap.py diff                print which generated files render would change, and exit 1 if any

Generated, overwritten on every render: JARVIS.md, config/jarvis.yaml, config/sources.yaml,
config/allowed_tools.yaml, config/holidays.md, config/scheduler/*.
Created once, then owned by the owner: OWNER.md, config/thresholds.md (render only appends the staleness key
of a newly enabled source), config/reactions.md.
Without a profile, render writes a skeleton in which only the bootstrap and dev modes can do anything.

After a render that changed config/ or JARVIS.md, re-pin the guard by hand: uv run scripts/guard_pin.py pin.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from datetime import date
from pathlib import Path
from typing import Any

import adapters
import common
import scheduler
import yaml
from adapters import InvalidSetup, Setup

GENERATED = "Generated by scripts/bootstrap.py render from profile/jarvis.profile.yaml; do not edit by hand."
PLACEHOLDER = re.compile(r"\{\{([a-zA-Z_]+)\}\}")
PRONOUNS = {
    "they": {"them": "them", "their": "their", "theirs": "theirs"},
    "he": {"them": "him", "their": "his", "theirs": "his"},
    "she": {"them": "her", "their": "her", "theirs": "hers"},
}
DAY_NAMES = {
    "mon": "Monday",
    "tue": "Tuesday",
    "wed": "Wednesday",
    "thu": "Thursday",
    "fri": "Friday",
    "sat": "Saturday",
    "sun": "Sunday",
}
DEFAULT_SCHEDULE = {
    "morning": "08:00",
    "midday": "13:00",
    "eod": "18:00",
    "consolidate_minute": 30,
    "dream": "02:00",
}
DEFAULT_MODELS = {
    "morning": {"model": "opus", "max_turns": 400, "timeout_minutes": 40},
    "midday": {"model": "opus", "max_turns": 250, "timeout_minutes": 25},
    "eod": {"model": "opus", "max_turns": 300, "timeout_minutes": 25},
    "consolidate": {"model": "sonnet", "max_turns": 200, "timeout_minutes": 15},
    "dream": {"model": "opus", "max_turns": 150, "timeout_minutes": 20},
    "replay": {"model": "opus", "max_turns": 300, "timeout_minutes": 30},
    "first_run": {"model": "opus", "max_turns": 1500, "timeout_minutes": 120},
}
BOOTSTRAP_WRITABLE = ("profile/**", "OWNER.md", "adapters/sources/**")


def fill(template: str, values: dict[str, str]) -> str:
    """Replace every {{name}}; a name without a value is an error, so nothing renders half-filled."""
    missing = sorted({name for name in PLACEHOLDER.findall(template) if name not in values})
    if missing:
        raise InvalidSetup([f"template placeholders without a value: {missing}"])
    return PLACEHOLDER.sub(lambda match: values[match.group(1)], template)


def _code_list(values: list[Any]) -> str:
    return ", ".join(f"`{value}`" for value in values) if values else "(none configured)"


def _hours(profile: dict[str, Any]) -> dict[str, Any]:
    hours = profile.get("working_hours") or {}
    return {
        "days": hours.get("days") or ["mon", "tue", "wed", "thu", "fri"],
        "start": str(_clock(hours.get("start", "08:00"))),
        "end": str(_clock(hours.get("end", "18:00"))),
    }


def _clock(value: Any) -> Any:
    """A slot as HH:MM; YAML 1.1 reads an unquoted 13:00 as the sexagesimal integer 780."""
    if isinstance(value, int):
        return f"{value // 60:02d}:{value % 60:02d}"
    return value


def schedule_config(profile: dict[str, Any]) -> dict[str, Any]:
    """Slots from the profile; consolidate runs hourly at its minute through the working hours."""
    given = profile.get("schedule") or {}
    slots = {
        **DEFAULT_SCHEDULE,
        **{k: (v if k.startswith("consolidate") else _clock(v)) for k, v in given.items()},
    }
    hours = _hours(profile)
    start, end = int(hours["start"].split(":")[0]), int(hours["end"].split(":")[0])
    slots.setdefault("consolidate_hours", list(range(start, end + 1)))
    return slots


# The prompt


def prompt_values(root: Path, setup: Setup) -> dict[str, str]:
    """Every placeholder of templates/JARVIS.md.tmpl, from the profile, the adapters, and the fragments."""
    profile = setup.profile
    principal = profile["principal"]
    name = str(principal["name"])
    short = str(principal.get("short_name") or name.split()[0])
    pronoun = PRONOUNS.get(str(principal.get("pronouns", "they")).split("/")[0], PRONOUNS["they"])
    assistant = str((profile.get("assistant") or {}).get("name", "Jarvis"))
    hours = _hours(profile)
    slots = schedule_config(profile)
    files = profile.get("files") or {}
    scope = principal.get("scope", "work")
    fragments = common.load_yaml(root / "templates" / "prompt_fragments.yaml")
    base = {
        **pronoun,
        "principal": short,
        "short": short,
        "assistant": assistant,
        "role": str(principal["role"]).rstrip("."),
        "opinions": str(files.get("opinions") or ""),
        "voice": str(files.get("voice") or ""),
        "documents": str(principal.get("goal_documents") or fragments["default_goal_documents"]),
    }

    def frag(text: str) -> str:
        return fill(text, base)

    def chosen(key: str, present: Any) -> str:
        return frag(fragments[key]["set" if present else "unset"])

    return {
        **base,
        "ASSISTANT": assistant.upper(),
        "principal": name,
        "generated_notice": f"<!-- {GENERATED} Put your own additions in OWNER.md. -->",
        "emails": ", ".join(principal.get("emails") or []) or "none given",
        "focus_line": f"\n- Focus: {principal['focus']}" if principal.get("focus") else "",
        "timezone": str(profile["timezone"]),
        "working_days": _day_range(hours["days"]),
        "hours_start": hours["start"],
        "hours_end": hours["end"],
        "mission_context": fill(fragments["mission"][scope], {**base, "principal": name}),
        "personal_scope_exception": frag(fragments["personal_scope_exception"][scope]),
        "goal_documents": frag(fragments["goal_documents"]),
        "slot_morning": slots["morning"],
        "slot_midday": slots["midday"],
        "slot_eod": slots["eod"],
        "slot_dream": slots["dream"],
        "sources_block": _sources_block(setup.sources, base),
        "staleness_lines": _staleness_lines(setup.sources),
        "index_line": frag(fragments["index"][(profile.get("index") or {}).get("backend", "sqlite")]),
        "opinions_line": chosen("opinions", files.get("opinions")),
        "voice_line": chosen("voice", files.get("voice")),
        "voice_floor": chosen("voice_floor", files.get("voice")),
        "opinions_read": f"`{files['opinions']}`, " if files.get("opinions") else "",
        **_delivery_values(setup.delivery, fragments["delivery"], base),
    }


def _day_range(days: list[str]) -> str:
    ordered = [day for day in adapters.WEEKDAYS if day in days]
    indexes = [adapters.WEEKDAYS.index(day) for day in ordered]
    if len(ordered) > 2 and indexes == list(range(indexes[0], indexes[-1] + 1)):
        return f"{DAY_NAMES[ordered[0]]} to {DAY_NAMES[ordered[-1]]}"
    return ", ".join(DAY_NAMES[day] for day in ordered)


def _sources_block(sources: list[adapters.Source], base: dict[str, str]) -> str:
    """The numbered reading policy: each adapter's prompt.md, its params filled, and its id form."""
    if not sources:
        return "No sources are enabled. Say so in every report."
    blocks = []
    for number, source in enumerate(sources, 1):
        params = {
            key: _code_list(value) if isinstance(value, list) else str(value)
            for key, value in source.params.items()
        }
        lines = fill(source.prompt.strip(), {**base, **params}).splitlines()
        body = "".join(f"\n   {line}" if line else "\n" for line in lines[1:])
        blocks.append(f"{number}. {lines[0]} Cite as `{source.id_template}`.{body}")
    return "\n".join(blocks)


def _staleness_lines(sources: list[adapters.Source]) -> str:
    lines = [
        f"- Loop kind `{kind}`, {rule.get('description', kind)}: "
        f"`stale_{kind}_days` calendar days without movement."
        for source in sources
        for kind, rule in source.staleness.items()
    ]
    return "\n".join(lines) if lines else "- No source adds its own loop kind."


def _delivery_values(
    delivery: adapters.Delivery | None, fragments: dict[str, Any], base: dict[str, str]
) -> dict[str, str]:
    assert delivery is not None
    place = fill(delivery.place, base)
    tools = " or ".join(f"`{tool}`" for tool in delivery.tools)
    values = {
        **base,
        "place": place,
        "target": delivery.target or "",
        "tool": tools.strip("`"),
        "and_reactions": " and reactions" if delivery.reactions else "",
    }
    variant = fragments["posts" if delivery.posts else "file"]
    text = {key: fill(value, values) for key, value in variant.items()}
    if delivery.posts and delivery.reactions:
        text["snooze_line"] = text["snooze_line_reactions"]
    text.pop("snooze_line_reactions", None)
    return {**text, "delivery_block": fill(delivery.prompt.strip(), values)}


def render_prompt(root: Path, setup: Setup) -> str:
    if not setup.bootstrapped:
        return (
            f"# JARVIS\n\n<!-- {GENERATED} -->\n\n"
            "This Jarvis is not bootstrapped yet.\n"
            "In every mode but `bootstrap` and `dev`, say so in one line, "
            "point to `scripts/jarvis bootstrap`, and stop.\n"
            "In `bootstrap` mode, run the `bootstrap` skill.\n"
        )
    template = (root / "templates" / "JARVIS.md.tmpl").read_text()
    return fill(template, prompt_values(root, setup))


def render_owner(root: Path, setup: Setup, today: date) -> str:
    decisions = (setup.profile.get("decisions") or []) or ["(none recorded)"]
    return fill(
        (root / "templates" / "OWNER.md.tmpl").read_text(),
        {
            **prompt_values(root, setup),
            "today": today.isoformat(),
            "decisions": "\n".join(f"- {line}" for line in decisions),
        },
    )


# Config files


def sources_config(setup: Setup) -> dict[str, Any]:
    sources: dict[str, Any] = {}
    for source in setup.sources:
        entry: dict[str, Any] = {"adapter": source.name, "id": source.id_template, "match": source.match}
        if source.capture == "mcp":
            entry["tools"] = source.tools
        elif source.capture == "bash":
            entry["bash"] = list(source.bash)
        else:
            entry["read"] = source.folder
        sources[source.source] = entry
    return {"sources": sources}


def allowlist(root: Path, setup: Setup) -> dict[str, Any]:
    policy = common.load_yaml(root / "templates" / "allowed_tools.base.yaml")
    policy["protected_by_mode"]["bootstrap"] = [p for p in policy["protected"] if p not in BOOTSTRAP_WRITABLE]
    missing = [p for p in BOOTSTRAP_WRITABLE if p not in policy["protected"]]
    if missing:
        raise InvalidSetup([f"templates/allowed_tools.base.yaml must protect {missing} as whole globs"])
    policy["groups"]["sources"] = [tool for source in setup.sources for tool in source.tools]
    delivery = setup.delivery
    if delivery and delivery.posts:
        policy["groups"]["post"] = list(delivery.tools)
        spec = {
            "keys": list(delivery.keys),
            "target_key": delivery.target_key,
            "target": [delivery.target] if delivery.target_shape == "list" else delivery.target,
            "message_key": delivery.message_key,
            "thread_key": delivery.thread_key,
        }
        policy["constrained"] = {tool: dict(spec) for tool in delivery.tools}
    else:
        policy["constrained"] = {}
    readers = [list(source.bash) for source in setup.sources if source.capture == "bash"]
    for mode in policy["modes"].values():
        if "sources" in mode["tools"] and isinstance(mode["bash"], list):
            mode["bash"] = mode["bash"] + [r for r in readers if r not in mode["bash"]]
    return policy


def runtime_config(setup: Setup) -> dict[str, Any]:
    profile = setup.profile
    runtime = profile.get("runtime") or {}
    claude_bin = runtime.get("claude_bin") or shutil.which("claude") or "~/.local/bin/claude"
    config: dict[str, Any] = {
        "bootstrapped": setup.bootstrapped,
        "assistant": str((profile.get("assistant") or {}).get("name", "Jarvis")),
        "curation": str(profile.get("curation", "curate")),
        "timezone": str(profile.get("timezone", "UTC")),
        "working_days": _hours(profile)["days"],
        "claude_bin": str(claude_bin),
        "claude_config_dir": runtime.get("claude_config_dir"),
        "canary": bool(runtime.get("canary", True)),
        "canary_model": str(runtime.get("canary_model", "haiku")),
        "schedule": schedule_config(profile),
        "lock_wait_minutes": int(runtime.get("lock_wait_minutes", 15)),
        "modes": {
            mode: {**bounds, **((runtime.get("models") or {}).get(mode) or {})}
            for mode, bounds in DEFAULT_MODELS.items()
        },
        "eval_tolerance": float(runtime.get("eval_tolerance", 0.05)),
        "index": {"backend": (profile.get("index") or {}).get("backend", "sqlite")},
        "scheduler": scheduler.settings(profile),
    }
    if setup.delivery:
        config["delivery"] = {"adapter": setup.delivery.name, "posts": setup.delivery.posts}
    else:
        config["delivery"] = {"adapter": None, "posts": False}
    return config


def holidays_md(setup: Setup, today: date) -> str:
    """Public holidays for this year and next from the `holidays` package, plus the profile's own days."""
    spec = setup.profile.get("holidays") or {}
    lines = [
        "# Holidays",
        "",
        f"<!-- {GENERATED} Add days off to `holidays.extra` in the profile. -->",
        "",
        "Business-day arithmetic skips every date listed here.",
        "One date per line, `YYYY-MM-DD name`.",
    ]
    entries: dict[str, str] = {}
    country = spec.get("country")
    if country:
        import holidays as holiday_calendars

        calendar = holiday_calendars.country_holidays(
            country, subdiv=spec.get("subdivision"), years=[today.year, today.year + 1]
        )
        entries.update({day.isoformat(): name for day, name in calendar.items()})
    for extra in spec.get("extra") or []:
        day, _, name = str(extra).partition(" ")
        date.fromisoformat(day)
        entries[day] = name or "day off"
    for year in sorted({day[:4] for day in entries}):
        lines += ["", f"## {year}", ""]
        lines += [f"- {day} {entries[day]}" for day in sorted(entries) if day.startswith(year)]
    return "\n".join(lines) + "\n"


def thresholds_md(root: Path, setup: Setup) -> str:
    """The owner's thresholds, with the staleness key of any newly enabled source appended."""
    path = root / "config" / "thresholds.md"
    text = path.read_text() if path.exists() else (root / "templates" / "thresholds.md").read_text()
    present = common.read_kv(path) if path.exists() else common.read_kv(root / "templates" / "thresholds.md")
    added = [
        f"stale_{kind}_days: {rule['days']}"
        for source in setup.sources
        for kind, rule in source.staleness.items()
        if f"stale_{kind}_days" not in present
    ]
    if added:
        text = text.rstrip("\n") + "\n\n" + "\n".join(added) + "\n"
    return text


def _dump(value: Any, header: str) -> str:
    body = yaml.safe_dump(value, sort_keys=False, allow_unicode=True, default_flow_style=None, width=110)
    return f"# {header}\n{body}"


def outputs(root: Path, setup: Setup, today: date) -> dict[str, str]:
    """Every generated file as repo-relative path -> content."""
    files = {
        "JARVIS.md": render_prompt(root, setup),
        "config/jarvis.yaml": _dump(runtime_config(setup), GENERATED + " Re-pin the guard after a change."),
        "config/sources.yaml": _dump(
            sources_config(setup), GENERATED + " Raw capture map for scripts/capture.py."
        ),
        "config/allowed_tools.yaml": _dump(allowlist(root, setup), GENERATED + " The guard's allowlist."),
        "config/holidays.md": holidays_md(setup, today),
        "config/thresholds.md": thresholds_md(root, setup),
    }
    if not (root / "config" / "reactions.md").exists():
        files["config/reactions.md"] = (root / "templates" / "reactions.md").read_text()
    if setup.bootstrapped and not (root / "OWNER.md").exists():
        files["OWNER.md"] = render_owner(root, setup, today)
    files.update(scheduler.render(root, runtime_config(setup)))
    return files


def changed(root: Path, files: dict[str, str]) -> list[str]:
    return [
        name
        for name, text in files.items()
        if not (root / name).exists() or (root / name).read_text() != text
    ]


def write(root: Path, files: dict[str, str]) -> list[str]:
    written = changed(root, files)
    for name in written:
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[name])
    unit_dir = root / "config" / "scheduler"
    if unit_dir.is_dir():
        for stale in unit_dir.iterdir():
            if stale.is_file() and f"config/scheduler/{stale.name}" not in files:
                stale.unlink()
                written.append(f"config/scheduler/{stale.name} (removed)")
    return written


def validate_all(root: Path) -> list[str]:
    """Problems in every shipped adapter (with default choices) and in the profile."""
    problems: list[str] = []
    for name in adapters.available(root, "sources"):
        try:
            adapters.load_source(root, name)
        except InvalidSetup as error:
            problems += error.problems
    try:
        adapters.load(root)
    except InvalidSetup as error:
        problems += error.problems
    return problems


def main(argv: list[str]) -> int:
    root = common.repo_root()
    today = common.now().date()
    try:
        match argv:
            case ["render"]:
                setup = adapters.load(root)
                written = write(root, outputs(root, setup, today))
                for name in written:
                    print(f"wrote {name}")
                if written:
                    print("re-pin the guard after reviewing the diff: uv run scripts/guard_pin.py pin")
                return 0
            case ["diff"]:
                names = changed(root, outputs(root, adapters.load(root), today))
                print("\n".join(names) if names else "up to date")
                return 1 if names else 0
            case ["validate"]:
                problems = validate_all(root)
                for problem in problems:
                    print(problem, file=sys.stderr)
                print("ok" if not problems else f"{len(problems)} problems")
                return 1 if problems else 0
            case ["adapters"]:
                listing = {kind: adapters.available(root, kind) for kind in ("sources", "delivery")}
                print(json.dumps(listing, indent=2))
                return 0
    except InvalidSetup as error:
        for problem in error.problems:
            print(problem, file=sys.stderr)
        return 1
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
